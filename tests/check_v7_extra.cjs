const fs=require('fs'),vm=require('vm'),assert=require('assert');
const base=require('path').join(__dirname,'../dist/');
const context={window:{},Set,Number,Array,JSON};vm.createContext(context);
vm.runInContext(fs.readFileSync(base+'stays-v7-data.js','utf8'),context);
const rows=context.window.STAY_RESEARCH;
assert.equal(rows.length,11);assert.equal(rows.filter(x=>x.original).length,8);
assert.equal(new Set(rows.map(x=>x.id)).size,11);
assert(rows.every(x=>!/[?]|token|userid/i.test(x.sourceUrl)));
assert(rows.filter(x=>x.priceType==='estimate').every(x=>/估算/.test(x.priceNote)));
assert.equal(rows.find(x=>x.id==='stay-qiri').total,null);
const workspace=fs.readFileSync(base+'workspace.js','utf8');
vm.runInContext(workspace.slice(workspace.indexOf('const tripChecks='),workspace.indexOf('window.normalizeWorkspaceState=')),context);
context.input={stayQuotes:{h8:2400,h9:2300,'alt-qinshu-chess':2200,'stay-yunqichuan':2250,bogus:1},selectedStay:'alt-qinshu-chess',tripChecks:{stay:{status:'checking',note:'旧备注'}},dayCompact:true};
const clean=vm.runInContext('normalizeWorkspaceState(input)',context);
assert.equal(clean.stayQuotes.h8,2400);assert.equal(clean.stayQuotes.h9,2300);
assert.equal(clean.stayQuotes['alt-qinshu-chess'],2200);assert.equal(clean.stayQuotes['stay-yunqichuan'],2250);
assert.equal(clean.stayQuotes.bogus,undefined);assert.equal(clean.selectedStay,'alt-qinshu-chess');
assert.equal(clean.tripChecks.stay.note,'旧备注');
context.input=JSON.parse(JSON.stringify(clean));assert.deepEqual(vm.runInContext('normalizeWorkspaceState(input)',context),clean);
console.log('PASS: research counts/price boundaries, clean source URLs, old and new lodging quotes and selection survive import.');
